import { YtdlError } from "./errors.ts";
import type { LookupOptions } from "./ytdl.ts";

export interface CaptionTrack {
  /** BCP 47 code such as `en` or `pt-BR`; `getCaptions` matches `lang` against it exactly. */
  readonly languageCode: string;
  readonly name: string;
  readonly isAutoGenerated: boolean;
  /** The track YouTube turns on first. */
  readonly isDefault: boolean;
  /** Signed by YouTube and expiring with the info; `getCaptions` requests it. */
  readonly url: string;
}

/**
 * Caption text formats YouTube renders.
 * @enum
 */
export const CaptionFormat = {
  /** WebVTT, which players, `ffmpeg` and `<track>` read directly. */
  Vtt: "vtt",
  /** YouTube's XML timed text with per-word timing and styling. */
  Srv3: "srv3",
  /** JSON events. */
  Json3: "json3",
} as const;

export type CaptionFormat = (typeof CaptionFormat)[keyof typeof CaptionFormat];

export interface CaptionOptions extends LookupOptions {
  /** Exact `languageCode` of a track. Without it: the default track, else the first manual track, else the first. */
  readonly lang?: string;
  /**
   * @defaultValue `CaptionFormat.Vtt`
   */
  readonly format?: CaptionFormat;
}

export function chooseTrack(tracks: readonly CaptionTrack[], lang: string | undefined): CaptionTrack {
  const found =
    lang === undefined
      ? (tracks.find((track) => track.isDefault) ?? tracks.find((track) => !track.isAutoGenerated) ?? tracks[0])
      : (tracks.find((track) => track.languageCode === lang && !track.isAutoGenerated) ??
        tracks.find((track) => track.languageCode === lang));
  if (found) return found;
  const offered = [...new Set(tracks.map((track) => track.languageCode))];
  throw new YtdlError(
    "NO_CAPTIONS",
    offered.length === 0
      ? "The video has no captions"
      : `No caption track in ${lang}; available: ${offered.join(", ")}`,
  );
}

export function captionUrl(track: CaptionTrack, format: CaptionFormat): string {
  const url = new URL(track.url);
  url.searchParams.set("fmt", format);
  return url.href;
}

export function checkFormat(format: string | undefined): void {
  if (format !== undefined && !Object.values<string>(CaptionFormat).includes(format)) {
    throw new YtdlError("INVALID_ARGUMENT", `format must be one of ${Object.values(CaptionFormat).join(", ")}`);
  }
}
