import { YtdlError } from "./errors.ts";
import { CaptionFormat, type CaptionTrack } from "./types.ts";

export function chooseTrack(tracks: readonly CaptionTrack[], lang: string | undefined): CaptionTrack {
  const found =
    lang === undefined
      ? (tracks.find((track) => track.isDefault) ?? tracks.find((track) => !track.isAutoGenerated) ?? tracks[0])
      : (tracks.find((track) => track.languageCode === lang && !track.isAutoGenerated) ??
        tracks.find((track) => track.languageCode === lang));
  if (found) return found;
  const offered = [...new Set(tracks.map((track) => track.languageCode))];
  throw new YtdlError(
    "NO_CAPTIONS",
    offered.length === 0
      ? "The video has no captions"
      : `No caption track in ${lang}; available: ${offered.join(", ")}`,
  );
}

export function captionUrl(track: CaptionTrack, format: CaptionFormat): string {
  const url = new URL(track.url);
  url.searchParams.set("fmt", format);
  return url.href;
}

export function checkFormat(format: string | undefined): void {
  if (format !== undefined && !Object.values<string>(CaptionFormat).includes(format)) {
    throw new YtdlError("INVALID_ARGUMENT", `format must be one of ${Object.values(CaptionFormat).join(", ")}`);
  }
}
