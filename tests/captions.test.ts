import { describe, expect, test } from "bun:test";
import { CaptionFormat, Ytdl, YtdlError } from "../src/index.ts";
import { fakeYouTube, fixture, playable } from "./fake-youtube.ts";

// Recorded 2026-10-20 from the VISIONOS player response for yuT7iQC-yro (NASA, public domain): `captions` kept as
// served, signatures, `ei` and `expire` replaced by placeholders, and a minimal playable body added.
const ID = "yuT7iQC-yro";
const RECORDED = fixture("captions-player.json");

interface RawTrack {
  readonly baseUrl: string;
  readonly languageCode: string;
  readonly name: { readonly runs: readonly { readonly text: string }[] };
  readonly kind?: string;
}
interface RawRenderer {
  readonly captionTracks: readonly RawTrack[];
  readonly audioTracks: readonly { readonly defaultCaptionTrackIndex: number }[];
  readonly defaultAudioTrackIndex?: number;
}
const renderer = (player: Record<string, unknown>) =>
  (player.captions as { playerCaptionsTracklistRenderer: RawRenderer }).playerCaptionsTracklistRenderer;

const withDefaultTrack = (index: number) => {
  const raw = renderer(RECORDED);
  const audioTracks = raw.audioTracks.map((track) => ({ ...track, defaultCaptionTrackIndex: index }));
  return { ...RECORDED, captions: { playerCaptionsTracklistRenderer: { ...raw, audioTracks } } };
};

interface TrackSpec {
  readonly lang: string;
  readonly asr?: boolean;
  readonly isDefault?: boolean;
}

function synthetic(tracks: readonly TrackSpec[], signature = "SECRET") {
  const defaultIndex = tracks.findIndex((track) => track.isDefault);
  return playable(ID, undefined, {
    captions: {
      playerCaptionsTracklistRenderer: {
        captionTracks: tracks.map((track, index) => ({
          baseUrl: `https://www.youtube.com/api/timedtext?v=${ID}&id=${index}&signature=${signature}&lang=${track.lang}`,
          name: { runs: [{ text: track.lang }] },
          languageCode: track.lang,
          ...(track.asr ? { kind: "asr" } : {}),
        })),
        audioTracks: defaultIndex < 0 ? [{}] : [{ defaultCaptionTrackIndex: defaultIndex }],
        defaultAudioTrackIndex: 0,
      },
    },
  });
}

const VTT = "WEBVTT\n\n00:00.000 --> 00:01.000\nhello\n";

function setup(player: Record<string, unknown>, timedtext: () => Response = () => new Response(VTT)) {
  const yt = fakeYouTube({
    player: () => player,
    media: (url) => (url.pathname === "/api/timedtext" ? timedtext() : undefined),
  });
  return {
    yt,
    ytdl: new Ytdl({ fetch: yt.fetch }),
    timedtext: () => yt.requests.filter((request) => request.url.includes("/api/timedtext")),
  };
}

async function rejection(promise: Promise<unknown>): Promise<YtdlError> {
  const error = await promise.then(
    () => undefined,
    (reason: unknown) => reason,
  );
  if (!(error instanceof YtdlError)) throw new Error(`Expected a YtdlError, got ${String(error)}`);
  return error;
}

describe("getInfo caption tracks", () => {
  test.each([
    ["as recorded", RECORDED],
    ["with the second track as the default", withDefaultTrack(1)],
  ])("lists every recorded track in order and flags one default, %s", async (_, player) => {
    const info = await new Ytdl({ fetch: setup(player).yt.fetch }).getInfo(ID);
    const raw = renderer(player);

    expect(info.captionTracks.map((track) => track.url)).toEqual(raw.captionTracks.map((track) => track.baseUrl));
    expect(info.captionTracks.map((track) => track.languageCode)).toEqual(
      raw.captionTracks.map((track) => track.languageCode),
    );
    expect(info.captionTracks.map((track) => track.name)).toEqual(
      raw.captionTracks.map((track) => track.name.runs[0]?.text ?? ""),
    );
    expect(info.captionTracks.map((track) => track.isAutoGenerated)).toEqual(
      raw.captionTracks.map((track) => track.kind === "asr"),
    );
    const defaults = info.captionTracks.flatMap((track, index) => (track.isDefault ? [index] : []));
    expect(defaults).toEqual([raw.audioTracks[raw.defaultAudioTrackIndex ?? 0]?.defaultCaptionTrackIndex ?? -1]);
  });

  test("a response without captions resolves with empty lists", async () => {
    const info = await new Ytdl({ fetch: setup(playable(ID)).yt.fetch }).getInfo(ID);
    expect(info.videoDetails.title).toBe(`Title of ${ID}`);
    expect(info.captionTracks).toEqual([]);
    expect(info.formats.length).toBeGreaterThan(0);
  });

  test.each(["baseUrl", "languageCode"])("drops a track without a %s", async (field) => {
    const player = synthetic([{ lang: "en" }, { lang: "fr" }]);
    const tracks = renderer(player).captionTracks as unknown as Record<string, unknown>[];
    delete tracks[0]?.[field];
    const info = await new Ytdl({ fetch: setup(player).yt.fetch }).getInfo(ID);
    expect(info.captionTracks.map((track) => track.name)).toEqual(["fr"]);
  });

  test("the default track comes from the default audio track, not the first", async () => {
    const player = synthetic([{ lang: "en" }, { lang: "ja" }]);
    const raw = renderer(player) as { audioTracks: unknown; defaultAudioTrackIndex: number };
    raw.audioTracks = [{ defaultCaptionTrackIndex: 0 }, { defaultCaptionTrackIndex: 1 }];
    raw.defaultAudioTrackIndex = 1;
    const { ytdl, timedtext } = setup(player);
    await ytdl.getCaptions(ID);
    expect(timedtext().map((request) => new URL(request.url).searchParams.get("lang"))).toEqual(["ja"]);
  });
});

describe("getCaptions track choice", () => {
  test.each<[string, readonly TrackSpec[], string | undefined, number]>([
    ["a manual track beats an auto-generated one listed first", [{ lang: "en", asr: true }, { lang: "en" }], "en", 1],
    ["an auto-generated track serves a lang with no manual one", [{ lang: "en", asr: true }, { lang: "fr" }], "en", 0],
    [
      "no lang picks the default over the first manual",
      [{ lang: "en" }, { lang: "ja", isDefault: true }],
      undefined,
      1,
    ],
    [
      "no lang and no default picks the first manual",
      [{ lang: "en", asr: true }, { lang: "fr" }, { lang: "de" }],
      undefined,
      1,
    ],
    ["no lang and only auto-generated tracks picks the first", [{ lang: "en", asr: true }], undefined, 0],
  ])("%s", async (_, tracks, lang, expected) => {
    const { ytdl, timedtext } = setup(synthetic(tracks));
    expect(await ytdl.getCaptions(ID, { lang })).toBe(VTT);
    expect(timedtext().map((request) => new URL(request.url).searchParams.get("id"))).toEqual([String(expected)]);
  });

  test.each<[string, readonly TrackSpec[], string, string]>([
    [
      "a language the video lacks names what it offers",
      [{ lang: "en" }, { lang: "en", asr: true }],
      "fr",
      "available: en",
    ],
    ["a base code does not match a regional one", [{ lang: "de-DE" }], "de", "available: de-DE"],
  ])("%s with NO_CAPTIONS and no timedtext request", async (_, tracks, lang, offered) => {
    const { ytdl, timedtext } = setup(synthetic(tracks));
    const error = await rejection(ytdl.getCaptions(ID, { lang }));
    expect(error.code).toBe("NO_CAPTIONS");
    expect(error.message).toContain(`in ${lang};`);
    expect(error.message).toContain(offered);
    expect(timedtext()).toEqual([]);
  });

  test("a video without captions rejects with NO_CAPTIONS", async () => {
    const { ytdl, timedtext } = setup(playable(ID));
    expect((await rejection(ytdl.getCaptions(ID))).code).toBe("NO_CAPTIONS");
    expect(timedtext()).toEqual([]);
  });
});

describe("getCaptions request", () => {
  test("defaults to WebVTT and returns the body unchanged", async () => {
    const { ytdl, timedtext } = setup(synthetic([{ lang: "en" }]));
    expect(await ytdl.getCaptions(ID)).toBe(VTT);
    expect(timedtext().map((request) => new URL(request.url).searchParams.get("fmt"))).toEqual(["vtt"]);
  });

  test("sends the requested format", async () => {
    const { ytdl, timedtext } = setup(synthetic([{ lang: "en" }]), () => new Response('{"events":[]}'));
    expect(await ytdl.getCaptions(ID, { format: CaptionFormat.Json3 })).toBe('{"events":[]}');
    expect(timedtext().map((request) => new URL(request.url).searchParams.get("fmt"))).toEqual(["json3"]);
  });

  test("rejects an unknown format before any request", async () => {
    const { ytdl, yt } = setup(synthetic([{ lang: "en" }]));
    const error = await rejection(ytdl.getCaptions(ID, { format: "xml" as CaptionFormat }));
    expect(error.code).toBe("INVALID_ARGUMENT");
    expect(yt.requests).toEqual([]);
  });

  test("rejects a URL that is not a video with INVALID_URL before any request", async () => {
    const { ytdl, yt } = setup(synthetic([{ lang: "en" }]));
    expect((await rejection(ytdl.getCaptions("https://example.com/watch?v=abcdefghijk"))).code).toBe("INVALID_URL");
    expect(yt.requests).toEqual([]);
  });
});

describe("getCaptions info reuse", () => {
  test("unexpired info makes one timedtext request and no player request", async () => {
    const { ytdl, yt, timedtext } = setup(synthetic([{ lang: "en" }]));
    const info = await ytdl.getInfo(ID);
    const before = yt.playerCalls.length;
    await ytdl.getCaptions(info);
    expect(yt.playerCalls.length).toBe(before);
    expect(timedtext()).toHaveLength(1);
  });

  test("expired info is looked up again and the new track URL is requested", async () => {
    let lookups = 0;
    const yt = fakeYouTube({
      player: () => synthetic([{ lang: "en" }], `SIG-${++lookups}`),
      media: (url) => (url.pathname === "/api/timedtext" ? new Response(VTT) : undefined),
    });
    const ytdl = new Ytdl({ fetch: yt.fetch });
    const stale = await ytdl.getInfo(ID);
    const staleSignature = new URL(stale.captionTracks[0]?.url ?? "").searchParams.get("signature");
    await ytdl.getCaptions({ ...stale, expiresAt: 0 });
    const requested = yt.requests.filter((request) => request.url.includes("/api/timedtext"));
    expect(requested).toHaveLength(1);
    const signature = new URL(requested[0]?.url ?? "").searchParams.get("signature");
    expect(signature).toStartWith("SIG-");
    expect(signature).not.toBe(staleSignature);
  });
});

describe("getCaptions failures", () => {
  test("HTTP 429 rejects with RATE_LIMITED", async () => {
    const { ytdl } = setup(synthetic([{ lang: "en" }]), () => new Response("", { status: 429 }));
    expect((await rejection(ytdl.getCaptions(ID))).code).toBe("RATE_LIMITED");
  });

  test("a thrown fetch rejects with REQUEST_FAILED, its cause and no signature", async () => {
    const yt = fakeYouTube({ player: () => synthetic([{ lang: "en" }]) });
    const network = new Error("socket hang up");
    const ytdl = new Ytdl({
      fetch: ((input: string | URL | Request, init?: RequestInit) =>
        String(input).includes("/api/timedtext") ? Promise.reject(network) : yt.fetch(input, init)) as typeof fetch,
    });
    const error = await rejection(ytdl.getCaptions(ID));
    expect(error.code).toBe("REQUEST_FAILED");
    expect(error.cause).toBe(network);
    expect(error.message).not.toContain("SECRET");
  });

  test("a body that stalls rejects with REQUEST_FAILED and a TimeoutError cause", async () => {
    const yt = fakeYouTube({
      player: () => synthetic([{ lang: "en" }]),
      media: (url) =>
        url.pathname === "/api/timedtext"
          ? new Response(
              new ReadableStream({ start: (controller) => controller.enqueue(new TextEncoder().encode("WEBVTT")) }),
            )
          : undefined,
    });
    const error = await rejection(new Ytdl({ fetch: yt.fetch, timeoutMs: 50 }).getCaptions(ID));

    expect(error.code).toBe("REQUEST_FAILED");
    expect(error.cause instanceof DOMException && error.cause.name).toBe("TimeoutError");
  });

  test("a signal aborted while the body streams rejects with its reason", async () => {
    const reason = new Error("stop");
    const caller = new AbortController();
    const yt = fakeYouTube({ player: () => synthetic([{ lang: "en" }]) });
    const streaming = (signal: AbortSignal | null | undefined) =>
      new Response(
        new ReadableStream({
          start: (controller) => {
            controller.enqueue(new TextEncoder().encode("WEBVTT"));
            signal?.addEventListener("abort", () => controller.error(signal.reason));
            caller.abort(reason);
          },
        }),
      );
    const ytdl = new Ytdl({
      fetch: (async (input: string | URL | Request, init?: RequestInit) =>
        String(input).includes("/api/timedtext") ? streaming(init?.signal) : yt.fetch(input, init)) as typeof fetch,
    });
    const info = await ytdl.getInfo(ID);

    expect(await ytdl.getCaptions(info, { signal: caller.signal }).catch((error: unknown) => error)).toBe(reason);
  });

  test.each<[string, string | undefined]>([
    ["a track is chosen", "en"],
    ["no track matches", "fr"],
  ])(
    "a signal aborted before the request rejects with its reason when %s, and makes no timedtext request",
    async (_, lang) => {
      const { ytdl, timedtext } = setup(synthetic([{ lang: "en" }]));
      const info = await ytdl.getInfo(ID);
      const reason = new Error("stop");
      const caught = await ytdl
        .getCaptions(info, { lang, signal: AbortSignal.abort(reason) })
        .catch((error: unknown) => error);
      expect(caught).toBe(reason);
      expect(timedtext()).toEqual([]);
    },
  );
});
